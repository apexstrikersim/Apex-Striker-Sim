fun nationFlagEmoji(codeOrName: String): String {
    val trimmed = codeOrName.trim()
    val code = if (trimmed.length == 3 && trimmed == trimmed.uppercase()) {
        trimmed
    } else {
        nationCodeForCountryName(trimmed) ?: trimmed.take(3).uppercase()
    }
    return when (code) {
        "ENG" -> "\uD83C\uDFF4\uDB40\uDC67\uDB40\uDC62\uDB40\uDC65\uDB40\uDC6E\uDB40\uDC67\uDB40\uDC7F"
        "SCO" -> "\uD83C\uDFF4\uDB40\uDC67\uDB40\uDC62\uDB40\uDC73\uDB40\uDC63\uDB40\uDC74\uDB40\uDC7F"
        "WAL" -> "\uD83C\uDFF4\uDB40\uDC67\uDB40\uDC62\uDB40\uDC77\uDB40\uDC6C\uDB40\uDC73\uDB40\uDC7F"
        else -> {
            val iso2 = NATION_CODE_TO_ISO2[code] ?: return "🏳️"
            if (iso2.length != 2) return "🏳️"
            val first = Character.toChars(0x1F1E6 + (iso2[0] - 'A'))
            val second = Character.toChars(0x1F1E6 + (iso2[1] - 'A'))
            String(first) + String(second)
        }
    }
}
